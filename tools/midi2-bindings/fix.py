# windows-bindgen emits non-compiling code for [NoException] static methods: the factory
# callback must return Result, but the method returns the bare value. Return Ok(..) from the
# callback and fall back to a zeroed value (false / None / 0) if the factory can't be loaded.
import re, sys
p = sys.argv[1]
s = open(p, encoding="utf-8").read()
pat = re.compile(r"(Self::I\w+\(\|this\| unsafe \{(?:(?!pub fn).)*?debug_assert!\(hresult__\.0 == 0\);\s*)(result__|core::mem::transmute\(result__\))(\s*\}\))", re.S)
s, n = pat.subn(lambda m: f"{m.group(1)}Ok({m.group(2)}){m.group(3)}.unwrap_or_else(|_| unsafe {{ core::mem::zeroed() }})", s)
open(p, "w", encoding="utf-8").write(s)
print("patched", n)

# The event subscription helpers need TypedEventHandler::new, which bindgen doesn't emit for this
# set of types. We don't use events, so drop the methods that build one.
s = open(p, encoding="utf-8").read()
removed = 0
while True:
    i = s.find(">>::new(move |a0, a1|")
    if i < 0:
        break
    start = s.rfind("pub fn ", 0, i)
    start = s.rfind("\n", 0, start) + 1
    # Skip the signature to the body's opening brace, then match braces.
    j = s.index("{", s.index("where", start) if s.find("where", start, i) != -1 else start)
    depth, k = 0, j
    while True:
        if s[k] == "{": depth += 1
        elif s[k] == "}":
            depth -= 1
            if depth == 0: break
        k += 1
    s = s[:start] + s[k + 1:].lstrip("\n")
    removed += 1
open(p, "w", encoding="utf-8").write(s)
print("removed event methods", removed)

s = open(p, encoding="utf-8").read()
header = "// Generated by tools/midi2-bindings (windows-bindgen + fix.py). Do not edit by hand.\n"
if not s.startswith(header):
    open(p, "w", encoding="utf-8").write(header + s)
